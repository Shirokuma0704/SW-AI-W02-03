"""
[기하 - Max Points on a Line]

▣ 출처
LeetCode 149. Max Points on a Line (Hard)
https://leetcode.com/problems/max-points-on-a-line/

▣ 상황 설명
X-Y 평면 위의 점들이 points 로 주어집니다. points[i] = [xi, yi] 입니다.
이 중 한 직선 위에 놓인 점이 최대 몇 개인지 구하세요.

    points = [[1,1],[3,2],[5,3],[4,1],[2,3],[1,4]
     b=]

      y
      4 |  o                       (1,4)
      3 |     o        o           (2,3) (5,3)
      2 |        o                 (3,2)
      1 |  o        o              (1,1) (4,1)
        +------------------ x
           1  2  3  4  5

    (1,1) (2,3) ... 처럼 여러 직선이 가능하지만,
    가장 많은 점을 지나는 직선 위에는 4 개가 놓여 있습니다.

▣ 목표
같은 직선 위에 놓인 점의 최대 개수를 정수로 반환.

▣ 규칙 (읽을 때 주의할 것)
  (1) 직선은 무한히 뻗는다. 선분이 아니다. 점들 사이가 아무리 떨어져 있어도
      한 직선 위이기만 하면 같이 센다.
  (2) 직선이 어느 점에서 시작하는지는 정해져 있지 않다. 가장 좋은 직선이
      points[0] 을 지난다는 보장이 없다.
  (3) 점 두 개면 언제나 직선 하나가 지나간다. 그래서 점이 2 개 이상이면
      답은 최소 2 다. 점이 1 개뿐이면 답은 1.
  (4) 모든 점은 서로 다르다. 같은 좌표가 중복해서 들어오지 않는다.
  (5) 좌표는 음수일 수 있다.

▣ 예시
    points = [[1,1],[2,2],[3,3]]                       ->  3
        세 점이 모두 y = x 위에 있다.

    points = [[1,1],[3,2],[5,3],[4,1],[2,3],[1,4]]     ->  4
        (1,4) (2,3) (3,2) (4,1) 이 한 직선 위에 있다.

▣ 구현할 함수
max_points(points: list) -> int
  - points 중 한 직선 위에 놓인 점의 최대 개수를 반환합니다.
  - 리트코드에서는 메서드 이름이 maxPoints(self, points) 입니다.
    로컬에서는 아래 이름을 그대로 두고, 제출할 때만 클래스 안에 옮겨 담으세요.
    (이름을 바꿔버리면 아래 테스트 하네스가 못 찾습니다)

▣ 제약
- 1 <= len(points) <= 300
- len(points[i]) == 2
- -10^4 <= xi, yi <= 10^4
- 모든 점은 서로 다르다.

▣ 생각해볼 것 (원문에 Follow up 은 없습니다)
- 점이 300 개면 두 점을 고르는 경우의 수가 약 45,000 가지다.
  거기서 다시 전체를 훑으면 1,300 만 번이 넘는다. 이보다 빠르게 갈 수 있을까?
- "두 점이 같은 직선 위.에 있다" 를 무엇으로 판정할지가 이 문제의 전부다.
  판정 기준을 무엇으로 잡느냐에 따라 아래 함정들을 밟기도 하고 안 밟기도 한다

▣ 함정 - 기울기를 나눗셈으로 구할 때
  (1) 수직선에서 x 차이가 0 이 된다. 그대로 나누면 ZeroDivisionError 로 죽는다.
      예외 처리로 때우기 전에, 애초에 나누지 않는 방법이 있는지 먼저 생각해보자.

  (2) 부동소수점(float)으로 기울기를 비교하면 "같아야 할 값이 미세하게 다르다"
      가 생길 수 있다. 이 문제의 좌표 범위(-10^4 ~ 10^4)에서는 운 좋게 통과하지만,
      범위가 조금만 커지면 바로 무너진다. 실제로 리트코드 149 는 좌표 범위가
      더 컸던 시절 float 풀이를 떨어뜨리는 테스트로 유명했다.
      정수만 써서 판정할 수 2다면 그쪽이 안전하다.

  (3) 두 방향을 "같은 방향" 으로 볼지가 애매해지는 순간이 있다.
      (0,0) 에서 (2,4) 로 가는 방향과 (0,0) 에서 (-2,-4) 로 가는 방향은
      가리키는 쪽이 반대지만 직선은 하나다. 이 둘을 다른 것으로 세면 틀린다.

▣ 참고 - 스스로 정답을 만들어 검증하는 법
새로운 입력에 대한 기댓값이 필요하면, 두 점을 모두 고른 뒤 나머지 점들이
그 직선 위에 있는지 하나씩 세는 완전탐색으로 답을 뽑을 수 있다.
느리지만 확실하다. (300 점에서는 오래 걸리니 작은 입력에만 쓸 것)
"세 점이 한 직선 위인가" 는 나눗셈 없이 정수 곱셈만으로 판정할 수 있다.
"""
from math import gcd
from collections import Counter


def max_points(points: list) -> int:
    """
    한 직선 위에 놓인 점의 최대 개수를 반환.

    예) max_points([[1,1],[2,2],[3,3]]) == 3
        max_points([[0,0]]) == 1
    """
    # TODO: 한 직선 위에 놓인 점의 최대 개수를 구해서 반환하세요.
    max_c = 1
    if len(points)<2:
        return len(points)

    for i in range(len(points)):
        d = Counter()
        for j in range(len(points)):
            if i == j:
                continue
            x_gain = points[i][0] - points[j][0]
            y_gain = points[i][1] - points[j][1]
            ratio = (x_gain // gcd(x_gain,y_gain), y_gain // gcd(x_gain,y_gain))
            d[ratio] += 1
        count = max(d.values())
        if max_c < count: max_c = count



    return max_c + 1

# ---------------------------------------------------------------------------
# 테스트
# ---------------------------------------------------------------------------
# 30 x 10 격자 = 300 점 (제약 상한). 한 가로줄에 30 개가 놓이므로 답은 30.
GRID = [[x, y] for y in range(10) for x in range(30)]

TEST_CASES = [
    # (points,                                            정답,  이 케이스가 잡아내는 것)
    ([[1, 1], [2, 2], [3, 3]],                              3,  "문제 예시 1"),
    ([[1, 1], [3, 2], [5, 3], [4, 1], [2, 3], [1, 4]],      4,  "문제 예시 2"),
    ([[0, 0]],                                              1,  "점이 하나 - 답은 0 이 아니라 1"),
    ([[0, 0], [1, 1]],                                      2,  "점이 둘 - 언제나 2"),
    ([[0, 0], [1, 0], [0, 1], [2, 3]],                      2,  "세 점이 한 줄에 없는 경우"),
    ([[1, 1], [1, 2], [1, 3], [5, 5]],                      3,  "수직선 - x 차이가 0"),
    ([[-1, -1], [-1, 0], [-1, 5], [3, 3]],                  3,  "음수 좌표 수직선"),
    ([[0, 4], [1, 4], [2, 4], [7, 0]],                      3,  "수평선 - y 차이가 0"),
    ([[0, 0], [3, 1], [6, 2], [9, 3]],                      4,  "기울기가 1/3 - 약분이 필요한 비율"),
    ([[0, 0], [2, 4], [-2, -4], [1, 0]],                    3,  "방향이 반대인 두 점 - 같은 직선으로 묶여야 함"),
    ([[0, 0], [-1, -1], [-2, -2], [-3, -3], [1, -1]],       4,  "전부 음수 방향"),
    ([[0, 0], [1, 2], [2, 4],
      [3, 1], [4, 1], [5, 1], [6, 1]],                      4,  "최적 직선이 points[0] 을 지나지 않음"),
    ([[1, 1], [2, 2], [3, 3],
      [1, 2], [2, 3], [3, 4], [4, 5]],                      4,  "기울기가 같은 평행선 둘 - 합쳐서 세면 안 됨"),
    ([[0, 0], [1, 1], [2, 2],
      [0, 1], [1, 2], [2, 3], [3, 4]],                      4,  "평행선 - 긴 쪽이 답"),
    (GRID,                                                 30,  "제약 상한 300 점 - 여기서 느리면 시간 초과"),
]


if __name__ == "__main__":
    print("[테스트] Max Points on a Line")
    print()

    passed = 0
    for points, expected, note in TEST_CASES:
        got = max_points([p[:] for p in points])
        ok = (got == expected)
        passed += ok
        mark = "PASS" if ok else "FAIL"
        label = f"<{len(points)}점>" if len(points) > 8 else str(points)
        print(f"  [{mark}] max_points({label}) -> {got}  (정답 {expected})")
        if not ok:
            print(f"         ^ {note}")

    print()
    print(f"  {passed} / {len(TEST_CASES)} 통과")
